-- Schema v9 — a video's thumbnail can be pinned to a moment (ADR-0024 stage 4).
--
-- The thumbnail does not stop being a function of the file; it becomes a
-- function of the file **and one number**. That is the whole design, and it is
-- what keeps invariant 1 intact: the journal records where to look and never
-- the pixels, so a rebuild replays `poster_set`, the derive pass re-extracts
-- the frame at that offset, and the picture comes back from `originals/` plus
-- the journal like every other derived artefact. Storing the image itself would
-- be base64 in a text file, which the forbidden-patterns list refuses twice.
--
-- NULL is the default and means "whatever the video backend picks" — a frame a
-- tenth of the way in, capped at ten seconds (`@roost/media`'s `frameTimestamp`).
-- Clearing is therefore the same decision as setting, with the value absent,
-- rather than a second operation.
--
-- Milliseconds, like a comment's `at_ms` and for the same reason: this is an
-- offset into a medium, not a date, and a second of granularity on a 24fps cut
-- is twenty-four frames of ambiguity.
--
-- No index. It is read one asset at a time, by the derive pass and by nothing
-- else, always beside the row it belongs to.

ALTER TABLE assets ADD COLUMN poster_ms INTEGER CHECK (poster_ms IS NULL OR poster_ms >= 0);
